
const mongoose = require("mongoose");

const paymentItemSchema = new mongoose.Schema(
  {
    productId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Product",
      required: true,
    },
    productName: String,
    productCode: String,
    price: Number,
    qty: Number,
    image: {
      url: String,
      public_id: String,
    },
    subtotal: Number,
  },
  { _id: false }
);

const paymentSchema = new mongoose.Schema(
  {
    userId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
    },

    amount: {
      type: Number,
      required: true,
    },

    currency: {
      type: String,
      default: "INR",
    },

    razorpayOrderId: {
      type: String,
      required: true,
      unique: true,
    },

    razorpayPaymentId: {
      type: String,
      default: null,
    },

    razorpaySignature: {
      type: String,
      default: null,
    },

    items: {
      type: [paymentItemSchema],
      required: true,
    },

    totalAmount: {
      type: Number,
      required: true,
    },

    totalItems: {
      type: Number,
      required: true,
    },

    orderId: {
      type: String,
      default: null,
    },

    paymentMethod: {
      type: String,
      default: null,
    },

    status: {
      type: String,
      enum: ["created", "paid", "failed"],
      default: "created",
    },
  },
  { timestamps: true }
);

module.exports = mongoose.model("Payment", paymentSchema);
